import { formatDate, formatRange } from "./dates.js";
import { money } from "./format.js";

const breakdownLabels = {
  accommodation: "Accommodation",
  food: "Food & drink",
  activities: "Activities",
  local_transport: "Local transport",
  miscellaneous: "Miscellaneous",
};
export { breakdownLabels };

export function toMarkdown(trip, itinerary, option) {
  const $ = (v) => money(v, trip.currency);
  const lines = [
    `# ${itinerary.trip_title}`,
    "",
    `**${trip.destination}** · ${formatRange(trip.startDate, trip.endDate)} · ${trip.days} days · ${trip.travellers} traveller${trip.travellers > 1 ? "s" : ""}`,
    `**Plan:** ${option.type} · **Estimated total:** ${$(option.estimated_total_cost)} (budget ${$(trip.budget)})`,
    "",
    "## Overview",
    itinerary.overview,
    "",
    option.summary,
    "",
    "## Cost breakdown",
    "| Category | Estimate |",
    "|---|---:|",
    ...Object.entries(breakdownLabels).map(([k, label]) => `| ${label} | ${$(option.cost_breakdown[k])} |`),
    `| **Total** | **${$(option.estimated_total_cost)}** |`,
    "",
    "## Day by day",
  ];
  for (const d of option.days) {
    lines.push("", `### Day ${d.day} · ${formatDate(d.date, { weekday: "short", day: "numeric", month: "short" })} — ${d.theme}`);
    for (const [label, s] of [["Morning", d.morning], ["Afternoon", d.afternoon], ["Evening", d.evening]]) {
      lines.push(`- **${label}: ${s.activity}** (${$(s.estimated_cost)}) — ${s.description}`);
    }
    lines.push(`- **Lunch:** ${d.food.lunch}`, `- **Dinner:** ${d.food.dinner}`);
  }
  lines.push("", "## Where to stay");
  for (const s of option.stays) {
    lines.push(`- **${s.name}** (${s.type}, ${s.area}) · ~${$(s.price_per_night)}/night — ${s.description}`);
  }
  lines.push(
    "", "## Getting around", itinerary.getting_around,
    "", "## When you're there", itinerary.best_time_notes,
    "", "## Tips", ...itinerary.travel_tips.map((t) => `- ${t}`),
    "", "## Packing list", ...itinerary.packing_list.map((t) => `- [ ] ${t}`),
    "", "---", "_Generated by Itinera. Costs are estimates; check prices and opening hours before booking._", "",
  );
  return lines.join("\n");
}

export function downloadFile(filename, content, type = "text/markdown") {
  const url = URL.createObjectURL(new Blob([content], { type }));
  const a = Object.assign(document.createElement("a"), { href: url, download: filename });
  document.body.append(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
